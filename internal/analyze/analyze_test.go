package analyze

import (
	"os"
	"os/exec"
	"path/filepath"
	"testing"
)

func gitIn(t *testing.T, dir string, args ...string) {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@t", "GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@t")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, out)
	}
}

func write(t *testing.T, dir, rel, content string) {
	t.Helper()
	p := filepath.Join(dir, rel)
	os.MkdirAll(filepath.Dir(p), 0o755)
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func fixture(t *testing.T) string {
	dir := t.TempDir()
	gitIn(t, dir, "init", "-q", "-b", "main")
	write(t, dir, "main.go", "package main\n\nfunc main() {}\n")
	write(t, dir, "a/b/c/deep.py", "x = 1\ny = 2\n")
	write(t, dir, "src/one.ts", "export const a = 1\n")
	write(t, dir, "src/two.ts", "export const b = 2\n")
	write(t, dir, "node_modules/x/index.js", "module.exports = 1\n")
	write(t, dir, "go.sum", "abc\n")
	write(t, dir, "gen.go", "// Code generated by foo. DO NOT EDIT.\npackage main\n")
	write(t, dir, "img.dat", "a\x00b")
	write(t, dir, "logo.png", "notreally")
	gitIn(t, dir, "add", "-A")
	gitIn(t, dir, "commit", "-q", "-m", "init")
	// uncommitted change must be ignored
	write(t, dir, "untracked.go", "package main\n")
	write(t, dir, "main.go", "changed\n")
	return dir
}

func TestRunLocal(t *testing.T) {
	c, err := Run(Options{Source: fixture(t)})
	if err != nil {
		t.Fatal(err)
	}
	if c.Stats.Files != 4 {
		t.Errorf("files = %d, want 4 (%+v)", c.Stats.Files, c.Stats.Skipped)
	}
	for r, n := range map[string]int{"vendored": 1, "lockfile": 1, "generated": 1, "binary": 2} {
		if c.Stats.Skipped[r] != n {
			t.Errorf("skipped[%s] = %d, want %d (%v)", r, c.Stats.Skipped[r], n, c.Stats.Skipped)
		}
	}
	var main *int
	for i, b := range c.Buildings {
		if b.Path == "main.go" {
			main = &c.Buildings[i].LOC
		}
		if b.Path == "untracked.go" {
			t.Error("untracked file included")
		}
		if b.W <= 0 || b.D <= 0 {
			t.Errorf("%s has empty footprint", b.Path)
		}
	}
	if main == nil || *main != 2 {
		t.Errorf("main.go should be measured from HEAD (2 LOC), got %v", main)
	}
	var collapsed bool
	for _, d := range c.Districts {
		if d.Path == "a/b/c" && d.Name == "a/b/c" {
			collapsed = true
		}
	}
	if !collapsed {
		t.Errorf("single-child chain not collapsed: %+v", c.Districts)
	}
	if c.Repo.Commit == "" || c.Repo.Ref != "main" {
		t.Errorf("repo = %+v", c.Repo)
	}
}

func TestRunFileURL(t *testing.T) {
	dir := fixture(t)
	c, err := Run(Options{Source: "file://" + dir, Ref: "main"})
	if err != nil {
		t.Fatal(err)
	}
	if c.Stats.Files != 4 {
		t.Errorf("files = %d", c.Stats.Files)
	}
}

func TestBadInputs(t *testing.T) {
	if _, err := Run(Options{Source: t.TempDir()}); err == nil {
		t.Error("non-repo should fail")
	}
	if _, err := Run(Options{Source: fixture(t), Ref: "--upload-pack=x"}); err == nil {
		t.Error("option-like ref should fail")
	}
	if _, err := Run(Options{Source: fixture(t), Ref: "nope"}); err == nil {
		t.Error("unknown ref should fail")
	}
}
