package scan

import "testing"

func TestMeasure(t *testing.T) {
	cases := []struct {
		in         string
		lines, loc int
	}{
		{"", 0, 0}, {"a", 1, 1}, {"a\n", 1, 1}, {"a\n\nb\n", 3, 2}, {"\n\n", 2, 0}, {"a\n  \nb", 3, 2},
	}
	for _, c := range cases {
		m := Measure([]byte(c.in))
		if m.Lines != c.lines || m.LOC != c.loc {
			t.Errorf("%q: got %+v want lines=%d loc=%d", c.in, m, c.lines, c.loc)
		}
	}
}

func TestLanguage(t *testing.T) {
	for p, want := range map[string]string{"a/b.go": "Go", "x.TSX": "TypeScript", "Dockerfile.dev": "Docker", "foo.zzz": "Other", "Makefile": "Makefile"} {
		if got := Language(p); got != want {
			t.Errorf("%s: %s != %s", p, got, want)
		}
	}
}

func TestPathSkip(t *testing.T) {
	o := Options{Excludes: []string{"*.snap", "docs/", "internal/x/*.go"}}
	cases := map[string]string{
		"src/a.go": "", "node_modules/x/y.js": "vendored", "a/vendor/b.go": "vendored", "go.sum": "lockfile",
		"a.min.js": "minified", "logo.PNG": "binary", "t/a.snap": "excluded", "docs/a.md": "excluded",
		"internal/x/a.go": "excluded", "internal/y/a.go": "",
	}
	for p, want := range cases {
		if got := PathSkip(p, "100644", 10, o); got != want {
			t.Errorf("%s: %q want %q", p, got, want)
		}
	}
	if PathSkip("a", "160000", 0, o) != "submodule" || PathSkip("a", "120000", 0, o) != "symlink" {
		t.Error("mode skips")
	}
	if PathSkip("big.txt", "100644", DefaultMaxBytes+1, o) != "large" {
		t.Error("large")
	}
	if PathSkip("node_modules/a.js", "100644", 1, Options{IncludeVendored: true}) != "" {
		t.Error("include vendored")
	}
}

func TestContentSkip(t *testing.T) {
	o := Options{}
	if ContentSkip([]byte("ab\x00cd"), o) != "binary" {
		t.Error("nul")
	}
	if ContentSkip([]byte("// Code generated by x. DO NOT EDIT.\npackage a"), o) != "generated" {
		t.Error("gen")
	}
	if ContentSkip([]byte("// Code generated by x. DO NOT EDIT.\n"), Options{IncludeGenerated: true}) != "" {
		t.Error("include gen")
	}
	if ContentSkip([]byte("package a"), o) != "" {
		t.Error("plain")
	}
}

func TestComplexity(t *testing.T) {
	src := "func a() {\n\tif x {\n\t\ty()\n\t}\n\n        z()\n}\n"
	if m := Measure([]byte(src)); m.Complexity != 1+2+1+2 {
		t.Errorf("complexity = %d", m.Complexity)
	}
}
